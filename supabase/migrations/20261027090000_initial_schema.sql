create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

-- -----------------------------------------------------------------------------
-- Staff / auth profiles
-- public.users.id mirrors auth.users.id
-- -----------------------------------------------------------------------------
create table if not exists public.users (
  id                    uuid primary key references auth.users (id) on delete cascade,
  name                  text not null,
  role                  text not null default 'doctor'
                          check (role in ('doctor', 'nurse', 'patient', 'admin')),
  email                 text,
  assigned_doctor_name  text,
  assigned_icu_ward     text,
  duty_start            time,
  duty_end              time,
  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now()
);

create unique index if not exists users_email_lower_key
  on public.users (lower(email))
  where email is not null;

-- -----------------------------------------------------------------------------
-- ICU units
-- -----------------------------------------------------------------------------
create table if not exists public.units (
  unit_id     bigint generated by default as identity primary key,
  unit_type   text not null unique,
  created_at  timestamptz not null default now()
);

-- -----------------------------------------------------------------------------
-- Patients (IDs are the human-readable codes used by the UI, e.g. P-1042)
-- -----------------------------------------------------------------------------
create table if not exists public.patients (
  id              text primary key,
  name            text not null,
  age             integer check (age is null or age between 0 and 130),
  gender          text,
  bed             integer,
  unit_id         bigint references public.units (unit_id) on delete set null,
  doctor_id       uuid references public.users (id) on delete set null,
  admission_type  text,
  admission_time  timestamptz not null default now(),
  diagnosis       text,
  status          text not null default 'stable'
                    check (status in ('stable', 'observing', 'critical', 'discharged')),
  qr_code         text,
  ot_hash_final   text,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

-- -----------------------------------------------------------------------------
-- Sentinel hash chain blocks
-- prev_hash contains the "sid=...|evt=frame|seq=..." metadata string used by
-- the serverless API, while curr_hash is the SHA-256 chain hash.
-- -----------------------------------------------------------------------------
create table if not exists public.ot_blocks (
  block_id     bigint generated by default as identity primary key,
  patient_id   text not null references public.patients (id) on delete cascade,
  bp           integer,
  spo2         numeric(5, 2),
  heart_rate   integer,
  prev_hash    text,
  curr_hash    text,
  recorded_at  timestamptz not null default now(),
  created_at   timestamptz not null default now()
);

-- -----------------------------------------------------------------------------
-- Doctor -> nurse / patient orders
-- -----------------------------------------------------------------------------
create table if not exists public.instructions (
  instruction_id  bigint generated by default as identity primary key,
  doctor_id       uuid references public.users (id) on delete set null,
  patient_id      text references public.patients (id) on delete cascade,
  nurse_id        uuid references public.users (id) on delete set null,
  text            text not null,
  status          text not null default 'pending'
                    check (status in ('pending', 'in_progress', 'completed', 'cancelled')),
  notes           text,
  completed_at    timestamptz,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

-- -----------------------------------------------------------------------------
-- Medication administration records
-- -----------------------------------------------------------------------------
create table if not exists public.administered (
  admin_id         bigint generated by default as identity primary key,
  doctor_id        uuid references public.users (id) on delete set null,
  patient_id       text references public.patients (id) on delete cascade,
  nurse_id         uuid references public.users (id) on delete set null,
  medicine         text not null,
  dosage           text,
  route            text default 'IV',
  is_administered  boolean not null default false,
  notes            text,
  administered_at  timestamptz,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);

-- -----------------------------------------------------------------------------
-- Patient complaints / nurse requests
--
-- The UI is inconsistent: PatientPortal writes `nature`, ICUCommandCenter reads
-- `complaint_text`. A trigger below keeps both columns in sync.
-- PatientPortal also writes status='active'; the trigger normalizes it to 'open'
-- so the nurse/ICU queues (which filter on status='open') pick it up.
-- -----------------------------------------------------------------------------
create table if not exists public.complaints (
  complaint_id      bigint generated by default as identity primary key,
  patient_id        text references public.patients (id) on delete cascade,
  nurse_id          uuid references public.users (id) on delete set null,
  doctor_id         uuid references public.users (id) on delete set null,
  lodged_by         text not null default 'patient',
  nature            text,
  complaint_text    text,
  status            text not null default 'open'
                      check (status in ('open', 'active', 'in_progress', 'resolved')),
  resolution_notes  text,
  resolved_by       text,
  resolved_at       timestamptz,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);

-- -----------------------------------------------------------------------------
-- Reports / documents
-- -----------------------------------------------------------------------------
create table if not exists public.reports (
  report_id    bigint generated by default as identity primary key,
  patient_id   text references public.patients (id) on delete cascade,
  report_type  text not null,
  status       text not null default 'verified',
  file_path    text,
  content      text,
  uploaded_by  uuid references public.users (id) on delete set null,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

-- -----------------------------------------------------------------------------
-- Chronos / ML risk prediction log
-- -----------------------------------------------------------------------------
create table if not exists public.risk_predictions (
  prediction_id    bigint generated by default as identity primary key,
  patient_id       text references public.patients (id) on delete cascade,
  event            text,
  risk_percentage  numeric(5, 2) check (risk_percentage is null or risk_percentage between 0 and 100),
  timeline         text,
  shap_1           text,
  shap_2           text,
  shap_3           text,
  model            text,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);

-- -----------------------------------------------------------------------------
-- Follow-up reminders shown in the patient portal
