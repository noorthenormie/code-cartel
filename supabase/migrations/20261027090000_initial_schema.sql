-- -----------------------------------------------------------------------------
-- Complaint compatibility trigger
-- -----------------------------------------------------------------------------
create or replace function public.sync_complaint_fields()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.nature is null and new.complaint_text is not null then
    new.nature := new.complaint_text;
  elsif new.complaint_text is null and new.nature is not null then
    new.complaint_text := new.nature;
  end if;

  if new.status = 'active' then
    new.status := 'open';
  end if;

  return new;
end;
$$;

drop trigger if exists complaints_sync_fields on public.complaints;
create trigger complaints_sync_fields
  before insert or update on public.complaints
  for each row execute function public.sync_complaint_fields();

-- -----------------------------------------------------------------------------
-- Create a public.users row whenever an auth.users row is created.
--
-- DoctorQuickAuth signs users up with metadata:
--   { name, role, assigned_doctor_name, assigned_icu_ward }
-- This trigger also covers signups where email confirmation is enabled and the
-- browser therefore has no authenticated session yet.
-- -----------------------------------------------------------------------------
create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_role text;
begin
  v_role := coalesce(new.raw_user_meta_data ->> 'role', 'doctor');

  if v_role not in ('doctor', 'nurse', 'patient', 'admin') then
    v_role := 'doctor';
  end if;

  insert into public.users as u (
    id,
    name,
    role,
    email,
    assigned_doctor_name,
    assigned_icu_ward
  )
  values (
    new.id,
    coalesce(
      nullif(new.raw_user_meta_data ->> 'name', ''),
      split_part(coalesce(new.email, 'user@synapse.local'), '@', 1)
    ),
    v_role,
    new.email,
    nullif(new.raw_user_meta_data ->> 'assigned_doctor_name', ''),
    nullif(new.raw_user_meta_data ->> 'assigned_icu_ward', '')
  )
  on conflict (id) do update
    set name                 = excluded.name,
        role                 = excluded.role,
        email                = excluded.email,
        assigned_doctor_name = coalesce(excluded.assigned_doctor_name, u.assigned_doctor_name),
        assigned_icu_ward    = coalesce(excluded.assigned_icu_ward, u.assigned_icu_ward),
        updated_at           = now();

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_auth_user();

-- Backfill profiles for auth users created before this migration.
insert into public.users (id, name, role, email, assigned_doctor_name, assigned_icu_ward)
select
  au.id,
  coalesce(
    nullif(au.raw_user_meta_data ->> 'name', ''),
    split_part(coalesce(au.email, 'user@synapse.local'), '@', 1)
  ),
  case
    when au.raw_user_meta_data ->> 'role' in ('doctor', 'nurse', 'patient', 'admin')
      then au.raw_user_meta_data ->> 'role'
    else 'doctor'
  end,
  au.email,
  nullif(au.raw_user_meta_data ->> 'assigned_doctor_name', ''),
  nullif(au.raw_user_meta_data ->> 'assigned_icu_ward', '')
from auth.users au
on conflict (id) do nothing;

